const fs = require("node:fs");
const path = require("node:path");
const net = require("node:net");
const { spawn, spawnSync } = require("node:child_process");
const mongoose = require("mongoose");
const { randomBytes } = require("node:crypto");
const { protectFile } = require("./tls.cjs");
const port = 27028,
  setName = "schoolDesktopRs";
const pause = (ms) => new Promise((resolve) => setTimeout(resolve, ms));
const same = (a, b) =>
  path.resolve(a).toLowerCase() === path.resolve(b).toLowerCase();
function findMongod(preferred) {
  const candidates = preferred ? [preferred] : [];
  const base = path.join(
    process.env.ProgramFiles || "C:\\Program Files",
    "MongoDB",
    "Server",
  );
  if (fs.existsSync(base))
    for (const version of fs
      .readdirSync(base)
      .sort((a, b) => b.localeCompare(a, undefined, { numeric: true })))
      candidates.push(path.join(base, version, "bin", "mongod.exe"));
  for (const item of (process.env.PATH || "").split(path.delimiter))
    if (item) candidates.push(path.join(item, "mongod.exe"));
  for (const file of candidates) {
    if (
      path.basename(file).toLowerCase() !== "mongod.exe" ||
      !fs.existsSync(file)
    )
      continue;
    const result = spawnSync(file, ["--version"], {
      windowsHide: true,
      timeout: 10000,
      encoding: "utf8",
    });
    const version = result.stdout?.match(/db version v(\d+)\.(\d+)\.(\d+)/);
    if (result.status === 0 && version && Number(version[1]) >= 7)
      return {
        path: fs.realpathSync(file),
        version: version[0].replace("db version v", ""),
      };
  }
  throw new Error(
    "MongoDB Server 7+ is required. Install the official Community Server and its Windows runtime, or choose an existing mongod.exe. No download, service or firewall change has been made.",
  );
}
const portOpen = () =>
  new Promise((resolve) => {
    const s = net.connect({ host: "127.0.0.1", port });
    s.setTimeout(500);
    s.once("connect", () => {
      s.destroy();
      resolve(true);
    });
    s.once("error", () => resolve(false));
    s.once("timeout", () => {
      s.destroy();
      resolve(false);
    });
  });
function authOptions(credentials, application = false) {
  if (!credentials?.adminPassword || !credentials?.appPassword)
    throw new Error(
      "Protected MongoDB credentials are missing; data was retained.",
    );
  return {
    auth: {
      username: application
        ? "schoolDesktopApplication"
        : "schoolDesktopSupervisor",
      password: application
        ? credentials.appPassword
        : credentials.adminPassword,
    },
    authSource: "admin",
  };
}
async function startMongo(root, binary, credentials) {
  authOptions(credentials);
  const folder = path.join(root, "mongodb"),
    data = path.join(folder, "data"),
    log = path.join(folder, "mongod.log"),
    cfg = path.join(folder, "mongod.cfg");
  fs.mkdirSync(data, { recursive: true });
  if (!same(fs.realpathSync(data), data) || !same(fs.realpathSync(root), root))
    throw new Error(
      "Persistent data folders must not be redirected through filesystem links.",
    );
  const legacy = `storage:\n  dbPath: ${JSON.stringify(data)}\nsystemLog:\n  destination: file\n  path: ${JSON.stringify(log)}\n  logAppend: true\nnet:\n  bindIp: 127.0.0.1\n  port: ${port}\nreplication:\n  replSetName: ${setName}\n`;
  const keyFile = path.join(folder, "replica.key");
  const configuration =
    legacy +
    `security:\n  authorization: enabled\n  keyFile: ${JSON.stringify(keyFile)}\n`;
  const previous = fs.existsSync(cfg) ? fs.readFileSync(cfg, "utf8") : null;
  if (previous && previous !== configuration && previous !== legacy)
    throw new Error(
      "MongoDB configuration differs from this preview profile. Existing data was not changed.",
    );
  // Upgrade only the exact profile generated by the previous desktop build.
  // Never adopt or stop an unrelated MongoDB instance.
  if (previous === legacy && (await portOpen())) {
    const old = new mongoose.mongo.MongoClient(
      `mongodb://127.0.0.1:${port}/?directConnection=true`,
      { serverSelectionTimeoutMS: 3000 },
    );
    try {
      await old.connect();
      await identify(old, data);
      try {
        await old.db("admin").command({ shutdown: 1 });
      } catch (error) {
        if (error.name !== "MongoNetworkError") throw error;
      }
    } finally {
      await old.close();
    }
    for (let i = 0; i < 120 && (await portOpen()); i++) await pause(500);
    if (await portOpen())
      throw new Error(
        "The old desktop database is still shutting down. Retry later; no data was removed.",
      );
  }
  if (!fs.existsSync(keyFile)) {
    if (previous === configuration)
      throw new Error(
        "MongoDB keyfile is missing. Restore the original security files; no key was replaced.",
      );
    fs.writeFileSync(keyFile, randomBytes(512).toString("base64"), {
      flag: "wx",
      mode: 0o600,
    });
  }
  if (fs.lstatSync(keyFile).isSymbolicLink())
    throw new Error("Refusing redirected MongoDB keyfile.");
  await protectFile(keyFile);
  if (previous === legacy && !fs.existsSync(cfg + ".pre-auth"))
    fs.copyFileSync(cfg, cfg + ".pre-auth", fs.constants.COPYFILE_EXCL);
  if (previous !== configuration) {
    fs.writeFileSync(cfg + ".next", configuration, { mode: 0o600 });
    fs.renameSync(cfg + ".next", cfg);
  }
  if (fs.existsSync(log) && fs.lstatSync(log).isSymbolicLink())
    throw new Error("Refusing redirected MongoDB log file.");
  let launched = false;
  if (!(await portOpen())) {
    const child = spawn(binary, ["--config", cfg], {
      windowsHide: true,
      detached: true,
      stdio: "ignore",
    });
    let failure;
    child.once("error", (e) => {
      failure = e;
    });
    child.unref();
    launched = true;
    for (let i = 0; i < 120; i++) {
      if (failure)
        throw new Error(
          "Windows could not start MongoDB. Check the MongoDB Server runtime prerequisite.",
        );
      if (await portOpen()) break;
      if (child.exitCode !== null)
        throw new Error(
          "MongoDB exited at startup. Check the profile mongodb/mongod.log; no other process was stopped.",
        );
      await pause(500);
    }
  }
  const client = new mongoose.mongo.MongoClient(
    `mongodb://127.0.0.1:${port}/?directConnection=true`,
    { serverSelectionTimeoutMS: 3000, ...authOptions(credentials) },
  );
  try {
    try {
      await client.connect();
    } catch (error) {
      if (!launched || error.code !== 18)
        throw new Error(
          "MongoDB authentication failed. Existing credentials and data were retained.",
        );
      const bootstrap = new mongoose.mongo.MongoClient(
        `mongodb://127.0.0.1:${port}/?directConnection=true`,
        { serverSelectionTimeoutMS: 3000 },
      );
      try {
        await bootstrap.connect();
        try {
          await bootstrap.db("admin").command({
            replSetInitiate: {
              _id: setName,
              members: [{ _id: 0, host: `127.0.0.1:${port}` }],
            },
          });
        } catch (e) {
          if (e.code !== 23) throw e;
        }
        for (let i = 0; i < 120; i++) {
          if (
            (await bootstrap.db("admin").command({ hello: 1 }))
              .isWritablePrimary
          )
            break;
          await pause(500);
        }
        // The localhost exception permits this only when no MongoDB users exist.
        await bootstrap.db("admin").command({
          createUser: "schoolDesktopSupervisor",
          pwd: credentials.adminPassword,
          roles: [{ role: "root", db: "admin" }],
          writeConcern: { w: "majority" },
        });
      } catch {
        throw new Error(
          "MongoDB security bootstrap could not complete. No business records were reset; retain the protected settings and inspect the local MongoDB log.",
        );
      } finally {
        await bootstrap.close();
      }
      await client.connect();
    }
    await identify(client, data);
    const security = (await client.db("admin").command({ getCmdLineOpts: 1 }))
      .parsed.security;
    if (
      security?.authorization !== "enabled" ||
      !same(security.keyFile || "", keyFile)
    )
      throw new Error(
        "MongoDB must enforce authentication using this installation's keyfile.",
      );
    let config;
    try {
      config = (await client.db("admin").command({ replSetGetConfig: 1 }))
        .config;
    } catch (e) {
      if (e.code !== 94 || !launched) throw e;
      await client.db("admin").command({
        replSetInitiate: {
          _id: setName,
          members: [{ _id: 0, host: `127.0.0.1:${port}` }],
        },
      });
    }
    if (
      config &&
      (config._id !== setName ||
        config.members.length !== 1 ||
        config.members[0].host !== `127.0.0.1:${port}`)
    )
      throw new Error(
        "Unexpected replica-set topology; refusing to adopt this server.",
      );
    let primary = false;
    for (let i = 0; i < 120; i++) {
      if ((await client.db("admin").command({ hello: 1 })).isWritablePrimary) {
        primary = true;
        break;
      }
      await pause(500);
    }
    if (!primary)
      throw new Error(
        "Local MongoDB did not become PRIMARY. Data has been retained.",
      );
    if (
      !(
        await client
          .db("admin")
          .command({ usersInfo: "schoolDesktopApplication" })
      ).users.length
    )
      await client.db("admin").command({
        createUser: "schoolDesktopApplication",
        pwd: credentials.appPassword,
        roles: [
          { role: "readWriteAnyDatabase", db: "admin" },
          { role: "dbAdminAnyDatabase", db: "admin" },
          { role: "clusterMonitor", db: "admin" },
        ],
      });
  } finally {
    await client.close();
  }
  return { port, setName, data };
}
async function identify(client, data) {
  const opts = (await client.db("admin").command({ getCmdLineOpts: 1 })).parsed;
  if (
    !opts.storage?.dbPath ||
    !same(opts.storage.dbPath, data) ||
    opts.net?.bindIp !== "127.0.0.1" ||
    opts.net.port !== port ||
    opts.replication?.replSetName !== setName
  )
    throw new Error(
      "Port 27028 belongs to another MongoDB instance. Its data and process were left alone.",
    );
}
async function stopMongo(root, credentials) {
  if (!(await portOpen())) return;
  const client = new mongoose.mongo.MongoClient(
    `mongodb://127.0.0.1:${port}/?directConnection=true`,
    { serverSelectionTimeoutMS: 3000, ...authOptions(credentials) },
  );
  try {
    await client.connect();
    await identify(client, path.join(root, "mongodb", "data"));
    try {
      await client.db("admin").command({ shutdown: 1 });
    } catch (e) {
      if (!["MongoNetworkError", "MongoServerSelectionError"].includes(e.name))
        throw e;
    }
  } finally {
    await client.close();
  }
  for (let i = 0; i < 120; i++) {
    if (!(await portOpen())) return;
    await pause(500);
  }
  throw new Error(
    "MongoDB is still shutting down. No process was force-killed.",
  );
}
module.exports = {
  findMongod,
  startMongo,
  stopMongo,
  port,
  setName,
  authOptions,
};
